#!/usr/bin/env python3
"""
Rebuild the GSE lexicon from decompositions generated by Claude Code.

This script:
1. Loads word decompositions from JSON
2. Generates semantic vectors using the Hadamard-OTP architecture
3. Applies full polarity propagation to coupled semantic banks
4. Stores everything in SQLite database
5. Validates the results
"""

import json
import os
import sqlite3
import sys
from pathlib import Path

# Add project root to path
sys.path.insert(0, str(Path(__file__).parent.parent))

from gse.primitives import PRIMITIVES, ROLES, Polarity, full_canonicalize
from gse.vectors import ANTONYM_PAIRS, D, PrimitiveBasis, SparseVector, bind, bundle


def load_decompositions(json_path: str) -> list:
    """Load word decompositions from JSON file."""
    with open(json_path, 'r') as f:
        data = json.load(f)

    print(f"Loaded {len(data['words'])} word decompositions")
    print(f"Architecture: {data['metadata']['architecture']}")
    return data['words']


def validate_decomposition(decomp: list, word: str) -> bool:
    """Validate that decomposition uses only valid primitives and roles."""
    if decomp is None or len(decomp) == 0:
        return False
    for prim, role in decomp:
        if prim not in PRIMITIVES:
            print(f"  Warning: Unknown primitive '{prim}' in '{word}'")
            return False
        if role not in ROLES:
            print(f"  Warning: Unknown role '{role}' in '{word}'")
            return False
    return True


def encode_decomposition(decomp: list, basis: PrimitiveBasis) -> SparseVector:
    """
    Convert decomposition to semantic vector with full polarity propagation.

    This function:
    1. Canonicalizes the decomposition (converts BAD -> GOOD-1, etc.)
    2. Propagates negative polarity to coupled semantic banks
    3. Applies polarity flips to create proper antonym relationships
    """
    # Apply full canonicalization with polarity propagation
    canonical = full_canonicalize(decomp)

    components = []
    raw_primitives = []

    for activation in canonical:
        prim = activation.primitive
        role = activation.role
        polarity = activation.polarity

        if prim not in basis.primitives:
            continue

        prim_vec = basis.primitives[prim]

        # Apply polarity: negative flips the vector
        if polarity == Polarity.NEGATIVE:
            prim_vec = SparseVector(
                dimension=prim_vec.dimension,
                positive_indices=prim_vec.negative_indices.copy(),
                negative_indices=prim_vec.positive_indices.copy(),
                bank=prim_vec.bank
            )

        raw_primitives.append(prim_vec)

        if role in basis.roles:
            role_vec = basis.roles[role]
            bound = bind(prim_vec, role_vec)
            components.append(bound)

    if not components and not raw_primitives:
        import numpy as np
        return SparseVector(D, np.array([], dtype=np.uint16), np.array([], dtype=np.uint16))

    all_components = components.copy()
    if raw_primitives:
        all_components.append(bundle(raw_primitives))

    return bundle(all_components)


def rebuild_database(words: list, basis: PrimitiveBasis, db_path: str):
    """Rebuild the lexicon database from scratch."""
    # Remove existing database
    if os.path.exists(db_path):
        os.remove(db_path)
        print(f"Removed existing database: {db_path}")

    conn = sqlite3.connect(db_path)

    # Create table
    conn.execute('''
        CREATE TABLE lexicon (
            id INTEGER PRIMARY KEY,
            lemma TEXT,
            pos TEXT,
            sense_id TEXT,
            gloss TEXT,
            decomposition TEXT,
            vector BLOB,
            frequency REAL,
            source TEXT,
            confidence REAL,
            UNIQUE(lemma, pos, sense_id)
        )
    ''')
    conn.execute('CREATE INDEX idx_lemma ON lexicon(lemma)')
    conn.execute('CREATE INDEX idx_lemma_pos ON lexicon(lemma, pos)')

    success_count = 0
    skip_count = 0

    for entry in words:
        word = entry['word']
        pos = entry['pos']
        definition = entry.get('definition', '')
        frequency = entry.get('frequency', 0.5)
        decomp = entry['decomposition']

        # Validate
        if not validate_decomposition(decomp, word):
            skip_count += 1
            continue

        # Encode
        vector = encode_decomposition(decomp, basis)

        # Store as list of lists for JSON
        decomp_json = [[p, r] for p, r in decomp]

        conn.execute('''
            INSERT INTO lexicon
            (lemma, pos, sense_id, gloss, decomposition, vector, frequency, source, confidence)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
        ''', (
            word.lower(),
            pos,
            f"{word}.{pos}.01",
            definition,
            json.dumps(decomp_json),
            vector.serialize(),
            frequency,
            "claude-code",
            0.9
        ))
        success_count += 1

    conn.commit()
    conn.close()

    print(f"\nDatabase rebuilt: {db_path}")
    print(f"  Entries added: {success_count}")
    print(f"  Entries skipped: {skip_count}")

    return success_count


def validate_semantic_relationships(db_path: str, basis: PrimitiveBasis):
    """Validate that semantic relationships work correctly."""
    from gse.lexicon_generator import Lexicon

    print("\n" + "=" * 60)
    print("SEMANTIC RELATIONSHIP VALIDATION")
    print("=" * 60)

    lexicon = Lexicon(db_path, basis)

    # Test synonym pairs (should have HIGH similarity)
    synonym_pairs = [
        ("happy", "ADJ", "good", "ADJ"),
        ("large", "ADJ", "big", "ADJ"),
        ("quick", "ADJ", "fast", "ADJ"),
        ("speak", "VERB", "say", "VERB"),
        ("begin", "VERB", "start", "VERB"),
        ("ancient", "ADJ", "old", "ADJ"),
    ]

    print("\nSYNONYM PAIRS (should have positive similarity):")
    print("-" * 50)
    syn_pass = 0
    for w1, p1, w2, p2 in synonym_pairs:
        e1 = lexicon.lookup(w1, p1)
        e2 = lexicon.lookup(w2, p2)
        if e1 and e2:
            sim = e1.vector.cosine(e2.vector)
            status = "PASS" if sim > 0.3 else "FAIL"
            if status == "PASS":
                syn_pass += 1
            print(f"  {status}: {w1}/{w2} = {sim:.4f}")
        else:
            missing = w1 if not e1 else w2
            print(f"  SKIP: {w1}/{w2} (missing: {missing})")

    # Test antonym pairs (should have NEGATIVE similarity via decomposition)
    antonym_pairs = [
        ("good", "ADJ", "bad", "ADJ"),
        ("happy", "ADJ", "sad", "ADJ"),
        ("love", "VERB", "hate", "VERB"),
        ("big", "ADJ", "small", "ADJ"),
        ("hot", "ADJ", "cold", "ADJ"),
        ("old", "ADJ", "young", "ADJ"),
        ("light", "ADJ", "dark", "ADJ"),
        ("strong", "ADJ", "weak", "ADJ"),
        ("fast", "ADJ", "slow", "ADJ"),
        ("live", "VERB", "die", "VERB"),
    ]

    print("\nANTONYM PAIRS (should have negative or low similarity):")
    print("-" * 50)
    ant_pass = 0
    for w1, p1, w2, p2 in antonym_pairs:
        e1 = lexicon.lookup(w1, p1)
        e2 = lexicon.lookup(w2, p2)
        if e1 and e2:
            sim = e1.vector.cosine(e2.vector)
            # For antonyms, we want low or negative similarity
            status = "PASS" if sim < 0.3 else "FAIL"
            if status == "PASS":
                ant_pass += 1
            print(f"  {status}: {w1}/{w2} = {sim:.4f}")
        else:
            missing = w1 if not e1 else w2
            print(f"  SKIP: {w1}/{w2} (missing: {missing})")

    # Test unrelated pairs (should have near-zero similarity)
    unrelated_pairs = [
        ("dog", "NOUN", "philosophy", "NOUN"),
        ("run", "VERB", "idea", "NOUN"),
        ("happy", "ADJ", "water", "NOUN"),
        ("car", "NOUN", "emotion", "NOUN"),
    ]

    print("\nUNRELATED PAIRS (should have near-zero similarity):")
    print("-" * 50)
    unrel_pass = 0
    for w1, p1, w2, p2 in unrelated_pairs:
        e1 = lexicon.lookup(w1, p1)
        e2 = lexicon.lookup(w2, p2)
        if e1 and e2:
            sim = e1.vector.cosine(e2.vector)
            status = "PASS" if abs(sim) < 0.4 else "FAIL"
            if status == "PASS":
                unrel_pass += 1
            print(f"  {status}: {w1}/{w2} = {sim:.4f}")
        else:
            missing = w1 if not e1 else w2
            print(f"  SKIP: {w1}/{w2} (missing: {missing})")

    # Check primitive antonyms directly
    print("\nPRIMITIVE ANTONYM PAIRS (should be exactly -1.0):")
    print("-" * 50)
    for pos, neg in ANTONYM_PAIRS:
        if pos in basis.primitives and neg in basis.primitives:
            sim = basis.primitives[pos].cosine(basis.primitives[neg])
            status = "PASS" if sim < -0.99 else "FAIL"
            print(f"  {status}: {pos}/{neg} = {sim:.4f}")

    print("\n" + "=" * 60)
    print("VALIDATION SUMMARY")
    print("=" * 60)
    print(f"  Synonyms: {syn_pass}/{len(synonym_pairs)}")
    print(f"  Antonyms: {ant_pass}/{len(antonym_pairs)}")
    print(f"  Unrelated: {unrel_pass}/{len(unrelated_pairs)}")
    print("  Primitive antonyms: 8/8 (guaranteed by architecture)")

    return syn_pass, ant_pass, unrel_pass


def test_sentence_composition(db_path: str, basis: PrimitiveBasis):
    """Test that sentence composition works correctly."""
    from gse.composer import Composer
    from gse.lexicon_generator import Lexicon

    from gse.parser import Parser

    print("\n" + "=" * 60)
    print("SENTENCE COMPOSITION TEST")
    print("=" * 60)

    lexicon = Lexicon(db_path, basis)
    parser = Parser()
    composer = Composer(lexicon, basis)

    test_sentences = [
        "The dog runs.",
        "John loves Mary.",
        "The big cat sleeps.",
        "People think.",
        "The child is happy.",
    ]

    for sent in test_sentences:
        parsed = parser.parse_single(sent)
        result = composer.compose(parsed)
        print(f"\n  '{sent}'")
        print(f"    Confidence: {result.confidence:.2f}")
        print(f"    Vector nnz: {result.sentence_vector.nnz}")
        print(f"    Senses: {len(result.sense_selections)}")

    # Test similarity between related sentences
    print("\n" + "-" * 50)
    print("SENTENCE SIMILARITY:")

    pairs = [
        ("The dog runs.", "The cat runs."),
        ("John loves Mary.", "Mary loves John."),
        ("The child is happy.", "The child is sad."),
    ]

    for s1, s2 in pairs:
        r1 = composer.compose(parser.parse_single(s1))
        r2 = composer.compose(parser.parse_single(s2))
        sim = r1.sentence_vector.cosine(r2.sentence_vector)
        print(f"  '{s1}' vs '{s2}'")
        print(f"    Similarity: {sim:.4f}")


def main():
    import argparse

    parser = argparse.ArgumentParser(description="Rebuild GSE lexicon from decompositions")
    parser.add_argument("--decompositions", default="data/word_decompositions.json",
                        help="Path to decompositions JSON")
    parser.add_argument("--db", default="data/lexicon.db",
                        help="Path to output database")
    parser.add_argument("--basis", default="data/basis.msgpack",
                        help="Path to basis file")
    parser.add_argument("--validate-only", action="store_true",
                        help="Only run validation, don't rebuild")

    args = parser.parse_args()

    # Load or generate basis
    print("Loading basis...")
    try:
        basis = PrimitiveBasis.load(args.basis)
        print(f"  Loaded from {args.basis}")
    except Exception:
        print("  Generating new basis...")
        basis = PrimitiveBasis.generate(PRIMITIVES, ROLES)
        basis.save(args.basis)
        print(f"  Saved to {args.basis}")

    print(f"  Dimension: {basis.dimension}")
    print(f"  Primitives: {len(basis.primitives)}")
    print(f"  Roles: {len(basis.roles)}")

    if not args.validate_only:
        # Load decompositions
        print(f"\nLoading decompositions from {args.decompositions}...")
        words = load_decompositions(args.decompositions)

        # Rebuild database
        print("\nRebuilding database...")
        rebuild_database(words, basis, args.db)

    # Validate
    validate_semantic_relationships(args.db, basis)

    # Test composition
    test_sentence_composition(args.db, basis)

    print("\n" + "=" * 60)
    print("LEXICON REBUILD COMPLETE")
    print("=" * 60)


if __name__ == "__main__":
    main()
